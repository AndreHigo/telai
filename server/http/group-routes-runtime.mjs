import { createGroupRuntime } from "../domain/groups/runtime.mjs";
import { createGroupDiscoveryRoutes } from "./group-discovery-routes.mjs";
import { createGroupManagementRoutes } from "./group-management-routes.mjs";
import { createGroupRoleRoutes } from "./group-role-routes.mjs";
import { createGroupRoomRoutes } from "./group-room-routes.mjs";
import { createGroupAuditRoutes } from "./group-audit-routes.mjs";
import { createGroupModerationRoutes } from "./group-moderation-routes.mjs";
import { createGroupContentRoutes } from "./group-content-routes.mjs";
import { createGroupInviteRoutes } from "./group-invite-routes.mjs";
import { createGroupRuntimeRoutes } from "./group-runtime-routes.mjs";
import { createGroupWebhookRoutes } from "./group-webhook-routes.mjs";

export function createGroupRoutesRuntime({
  json,
  readJson,
  requireUser,
  groupRepository,
  groupSettingsRepository,
  groupMemberRepository,
  groupJoinRequestRepository,
  groupPermissionRepository,
  groupSetupRepository,
  groupRoleRepository,
  groupAuditRepository,
  groupModerationRepository,
  groupInviteRepository,
  groupMessageRepository,
  groupAttachmentRepository,
  groupWebhookRepository,
  groupRoomPermissionRepository,
  groupRoomRepository,
  groupRoomReadRepository,
  groupPermissions,
  isGroupMember,
  canGroupAction,
  canGroupRoomAction,
  attachmentStorage,
  attachmentUrlFor,
  streamRepository,
  runtimeStreamIsLive,
  streamPublicPath,
  compactAvatarData,
  compactUserSummary,
  parseChannelGames,
  slugFor,
  roomSlugFor,
  parseVoiceRoomParticipantLimit,
  createNotification,
  sendGroupInviteEmail,
  publicOriginForRequest,
  warnLog,
  randomBytes,
  hashToken,
  createToken,
  groupPresence,
  voiceRooms,
  send,
  leaveVoiceRoom,
  voiceParticipantFor,
  touchGroupPresence,
  isPresent,
  disconnectUserFromGroup,
  publishGroupPresence,
  publishGroupEvent,
}) {
  const { disconnectGroupUser } = createGroupRuntime({
    voiceRooms,
    groupPresence,
    send,
    leaveVoiceRoom,
    disconnectUserFromGroup,
    publishGroupPresence,
  });
  const handleGroupDiscoveryRoutes = createGroupDiscoveryRoutes({
    json,
    readJson,
    requireUser,
    groupRepository,
    groupSettingsRepository,
    groupMemberRepository,
    slugFor,
  });
  const handleGroupManagementRoutes = createGroupManagementRoutes({
    json,
    readJson,
    requireUser,
    groupJoinRequestRepository,
    groupSettingsRepository,
    groupPermissionRepository,
    groupSetupRepository,
    groupRoleRepository,
    groupAuditRepository,
    groupModerationRepository,
    groupInviteRepository,
    isGroupMember,
    createNotification,
    slugFor,
  });
  const handleGroupRoleRoutes = createGroupRoleRoutes({ json, readJson, requireUser, groupRoleRepository, groupPermissionRepository, groupAuditRepository });
  const handleGroupRoomRoutes = createGroupRoomRoutes({
    json,
    readJson,
    requireUser,
    isGroupMember,
    canGroupAction,
    groupRoleRepository,
    groupRoomPermissionRepository,
    groupPermissionRepository,
    groupRoomRepository,
    groupAuditRepository,
    roomSlugFor,
    parseVoiceRoomParticipantLimit,
  });
  const handleGroupAuditRoutes = createGroupAuditRoutes({ json, requireUser, groupPermissionRepository, groupAuditRepository });
  const handleGroupModerationRoutes = createGroupModerationRoutes({
    json,
    readJson,
    requireUser,
    groupPermissions,
    groupMemberRepository,
    groupModerationRepository,
    groupAuditRepository,
    disconnectGroupUser,
    publishGroupEvent,
  });
  const handleGroupContentRoutes = createGroupContentRoutes({
    json,
    readJson,
    requireUser,
    isGroupMember,
    canGroupAction,
    groupMessageRepository,
    groupAttachmentRepository,
    attachmentStorage,
    attachmentUrlFor,
    canGroupRoomAction,
    groupPermissionRepository,
    groupModerationRepository,
    publishGroupEvent,
  });
  const handleGroupWebhookRoutes = createGroupWebhookRoutes({
    json,
    readJson,
    requireUser,
    groupSettingsRepository,
    groupRoomRepository,
    groupMessageRepository,
    groupWebhookRepository,
    hashToken,
    createToken,
    publishGroupEvent,
    publicOriginForRequest,
  });
  const handleGroupInviteRoutes = createGroupInviteRoutes({
    json,
    readJson,
    requireUser,
    groupInviteRepository,
    groupPermissionRepository,
    groupSettingsRepository,
    isGroupMember,
    canGroupAction,
    createNotification,
    sendGroupInviteEmail,
    publicOriginForRequest,
    warnLog,
    compactUserSummary,
    randomBytes,
  });
  const handleGroupRuntimeRoutes = createGroupRuntimeRoutes({
    json,
    requireUser,
    groupJoinRequestRepository,
    groupSettingsRepository,
    groupRoomRepository,
    groupRoomReadRepository,
    groupMemberRepository,
    groupMessageRepository,
    groupAttachmentRepository,
    attachmentStorage,
    attachmentUrlFor,
    streamRepository,
    groupPermissions,
    isGroupMember,
    runtimeStreamIsLive,
    streamPublicPath,
    compactAvatarData,
    parseChannelGames,
    voiceRooms,
    send,
    leaveVoiceRoom,
    voiceParticipantFor,
    touchGroupPresence,
    isPresent,
    canGroupRoomAction,
  });

  return {
    disconnectGroupUser,
    handleGroupDiscoveryRoutes,
    handleGroupManagementRoutes,
    handleGroupRoleRoutes,
    handleGroupRoomRoutes,
    handleGroupAuditRoutes,
    handleGroupModerationRoutes,
    handleGroupContentRoutes,
    handleGroupWebhookRoutes,
    handleGroupInviteRoutes,
    handleGroupRuntimeRoutes,
  };
}
